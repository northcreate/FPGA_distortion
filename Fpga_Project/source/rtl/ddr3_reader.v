`timescale 1ns / 1ps

// Phase-1 DDR read-command client for the existing fram_buf/wr_rd_ctrl_top path.
// This module is NOT a second AXI master. It submits one logical read command
// through the existing rd_cmd_* interface and consumes the returned 256-bit
// data stream. Verilog-2001 compatible.
module ddr3_reader #(
    parameter ADDR_WIDTH = 28,
    parameter DATA_WIDTH = 256,
    parameter COUNT_WIDTH = 16
) (
    input                         clk,
    input                         rstn,

    // Request side: one request is accepted when req_valid && req_ready.
    input                         req_valid,
    output                        req_ready,
    input      [ADDR_WIDTH-1:0]   req_addr,
    input      [31:0]             req_len,       // number of 256-bit data beats

    // Existing fram_buf/wr_rd_ctrl_top logical read-command interface.
    output reg                    rd_cmd_en,
    output reg [ADDR_WIDTH-1:0]   rd_cmd_addr,
    output reg [31:0]             rd_cmd_len,
    input                         rd_cmd_ready,
    input                         rd_cmd_done,

    // Data stream returned by the existing controller.
    input      [DATA_WIDTH-1:0]   rd_data,
    input                         rd_data_valid,
    output                        data_valid,
    output     [DATA_WIDTH-1:0]   data,
    output     [COUNT_WIDTH-1:0]  data_index,

    // Status/debug signals.
    output                        busy,
    output reg                    done,
    output reg                    error,
    output reg [COUNT_WIDTH-1:0]  beats_seen,
    output reg [COUNT_WIDTH-1:0]  completed_beats,
    output reg [DATA_WIDTH-1:0]   first_data
);

    localparam [1:0] ST_IDLE     = 2'd0;
    localparam [1:0] ST_WAIT_CMD = 2'd1;
    localparam [1:0] ST_WAIT_END = 2'd2;

    reg [1:0] state;
    reg [ADDR_WIDTH-1:0] pending_addr;
    reg [31:0] pending_len;

    assign req_ready  = (state == ST_IDLE);
    assign busy       = (state != ST_IDLE);
    assign data_valid = (state == ST_WAIT_END) && rd_data_valid;
    assign data       = rd_data;
    // Beat index is zero-based and advances only on a valid returned beat.
    assign data_index = beats_seen;

    always @(posedge clk or negedge rstn) begin
        if (!rstn) begin
            state           <= ST_IDLE;
            pending_addr    <= {ADDR_WIDTH{1'b0}};
            pending_len     <= 32'd0;
            rd_cmd_en       <= 1'b0;
            rd_cmd_addr     <= {ADDR_WIDTH{1'b0}};
            rd_cmd_len      <= 32'd0;
            done            <= 1'b0;
            error           <= 1'b0;
            beats_seen      <= {COUNT_WIDTH{1'b0}};
            completed_beats <= {COUNT_WIDTH{1'b0}};
            first_data      <= {DATA_WIDTH{1'b0}};
        end else begin
            // rd_cmd_en is deliberately a one-clock pulse. The legacy
            // wr_cmd_trans detects its rising edge to capture address/length.
            rd_cmd_en <= 1'b0;
            done      <= 1'b0;

            case (state)
                ST_IDLE: begin
                    if (req_valid) begin
                        pending_addr    <= req_addr;
                        pending_len     <= req_len;
                        beats_seen      <= {COUNT_WIDTH{1'b0}};
                        completed_beats <= {COUNT_WIDTH{1'b0}};
                        first_data      <= {DATA_WIDTH{1'b0}};
                        error           <= 1'b0;

                        if (req_len == 32'd0) begin
                            error <= 1'b1;
                            done  <= 1'b1;
                            state <= ST_IDLE;
                        end else begin
                            state <= ST_WAIT_CMD;
                        end
                    end
                end

                ST_WAIT_CMD: begin
                    // Wait until the existing command scheduler is free.
                    if (rd_cmd_ready) begin
                        rd_cmd_addr <= pending_addr;
                        rd_cmd_len  <= pending_len;
                        rd_cmd_en   <= 1'b1;
                        state       <= ST_WAIT_END;
                    end
                end

                ST_WAIT_END: begin
                    if (rd_data_valid) begin
                        if (beats_seen < pending_len[COUNT_WIDTH-1:0]) begin
                            beats_seen <= beats_seen + {{(COUNT_WIDTH-1){1'b0}},1'b1};
                            if (beats_seen == {COUNT_WIDTH{1'b0}})
                                first_data <= rd_data;
                        end else begin
                            // More data arrived than the requested logical length.
                            error <= 1'b1;
                        end
                    end

                    // rd_cmd_done is generated by the existing command layer.
                    // Include a same-cycle valid beat in the final comparison.
                    if (rd_cmd_done) begin
                        if ((beats_seen + (rd_data_valid ? {{(COUNT_WIDTH-1){1'b0}},1'b1}
                                                            : {COUNT_WIDTH{1'b0}}))
                            != pending_len[COUNT_WIDTH-1:0]) begin
                            error <= 1'b1;
                        end
                        completed_beats <= beats_seen +
                                           (rd_data_valid ? {{(COUNT_WIDTH-1){1'b0}},1'b1}
                                                          : {COUNT_WIDTH{1'b0}});
                        done  <= 1'b1;
                        state <= ST_IDLE;
                    end
                end

                default: begin
                    state <= ST_IDLE;
                    error <= 1'b1;
                end
            endcase
        end
    end

endmodule
